// Regenerate src/tags.generated.ts from ../tools/cdx_tags.json, which
// tools/extract_tags.py derives from Revvity's CDXConstants.h (BSD-3).
//
// Usage: node scripts/gen-tags.ts
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

interface PropertyEntry {
  name: string;
  section: string | null;
  type: string | null;
  aliases?: string[];
}
interface TagFile {
  objects: Record<string, string>;
  properties: Record<string, PropertyEntry>;
}

const here = dirname(fileURLToPath(import.meta.url));
const source = join(here, "..", "..", "tools", "cdx_tags.json");
const target = join(here, "..", "src", "tags.generated.ts");
const tags = JSON.parse(readFileSync(source, "utf8")) as TagFile;

const byValue = (a: string, b: string): number => Number(a) - Number(b);
const objects = Object.keys(tags.objects)
  .sort(byValue)
  .map((key) => `  [${key}, ${JSON.stringify(tags.objects[key])}],`);
const properties = Object.keys(tags.properties)
  .sort(byValue)
  .map((key) => {
    const p = tags.properties[key];
    if (p === undefined) throw new Error(`missing property ${key}`);
    return `  [${key}, { name: ${JSON.stringify(p.name)}, type: ${JSON.stringify(p.type)} }],`;
  });

const out = `// GENERATED by scripts/gen-tags.ts from tools/cdx_tags.json — do not edit.
// Source: Revvity open-source ChemDraw file format code, CDXConstants.h (BSD-3-Clause).

export interface PropertyTagInfo {
  readonly name: string;
  /** Data type named in the CDXConstants.h comment, or null when absent. */
  readonly type: string | null;
}

export const OBJECT_TAGS: ReadonlyMap<number, string> = new Map([
${objects.join("\n")}
]);

export const PROPERTY_TAGS: ReadonlyMap<number, PropertyTagInfo> = new Map([
${properties.join("\n")}
]);
`;
writeFileSync(target, out);
console.log(
  `wrote ${target}: ${objects.length} objects, ${properties.length} properties`,
);

// ---- CDXML tables (tools/cdxml_tables.json from extract_cdxml.py) ----------

interface CdxmlFile {
  objects: Record<string, string>;
  attributes: Record<string, string>;
  enums: Record<string, { cpp_type: string; values: Array<[number, string]> }>;
  bindings: Record<string, { table: string; tokens: boolean }>;
  scales: Record<string, string>;
}
const cdxml = JSON.parse(
  readFileSync(join(here, "..", "..", "tools", "cdxml_tables.json"), "utf8"),
) as CdxmlFile;
const entries = (r: Record<string, unknown>): string[] =>
  Object.keys(r)
    .sort(byValue)
    .map((k) => `  [${k}, ${JSON.stringify(r[k])}],`);
const enumLines = Object.keys(cdxml.enums)
  .sort()
  .map(
    (k) => `  ${JSON.stringify(k)}: ${JSON.stringify(cdxml.enums[k]?.values)},`,
  );
const cdxmlTarget = join(here, "..", "src", "cdxml.tables.generated.ts");
writeFileSync(
  cdxmlTarget,
  `// GENERATED by scripts/gen-tags.ts from tools/cdxml_tables.json — do not edit.
// Source: Revvity open-source ChemDraw file format code (BSD-3-Clause):
// CDXMLParser.cpp / XMLObjectName() element names, CDXObject.cpp attribute
// names, XMLPutEnum tables and the XMLStoreAttribute bindings that use them.

/** CDX object tag -> CDXML element name. */
export const CDXML_ELEMENTS: ReadonlyMap<number, string> = new Map([
${entries(cdxml.objects).join("\n")}
]);

/** CDX property tag -> CDXML attribute name. */
export const CDXML_ATTRIBUTES: ReadonlyMap<number, string> = new Map([
${entries(cdxml.attributes).join("\n")}
]);

/** XMLPutEnum tables: [numeric value, CDXML text]. */
export const CDXML_ENUMS: Readonly<Record<string, ReadonlyArray<readonly [number, string]>>> = {
${enumLines.join("\n")}
};

/** Property tag -> value scaling used by Revvity's CDXML writers. */
export const CDXML_SCALES: ReadonlyMap<number, "tenths" | "angle" | "coordinate" | "hex"> = new Map([
${entries(cdxml.scales).join("\n")}
]);

/** Property tag -> enum table; tokens = space-separated flag set. */
export const CDXML_BINDINGS: ReadonlyMap<number, { readonly table: string; readonly tokens: boolean }> = new Map([
${entries(cdxml.bindings).join("\n")}
]);
`,
);
console.log(`wrote ${cdxmlTarget}`);
